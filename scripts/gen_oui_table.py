"""Generates src/activities/utilities/OuiVendors.h from scripts/data/oui_vendors.tsv.

A curated subset of IEEE OUI assignments (not the full ~56k-entry Wireshark
manuf database, which would cost hundreds of KB of flash for little benefit
here): every Espressif Inc prefix (ESP32/ESP8266 boards -- the hardware most
DIY WiFi/BLE attack tools run on), Raspberry Pi's clean /24 prefixes, Flipper
Zero's prefixes (shared with the BLE device finder), and a curated sample of
common consumer/networking vendors, so an unrecognized MAC reads as "Unknown"
rather than every MAC reading as unknown.

Source data (scripts/data/oui_vendors.tsv) was extracted from `tshark -G
manuf` (Wireshark's bundled, authoritative OUI database) plus two Flipper
Devices Inc prefixes not yet in that database (sourced from maclookup.app via
the Wall-of-Flippers project, MIT licensed, reimplemented independently here).
Tab-separated: OUI (XX:XX:XX), short vendor name (<=12 chars, already sized
for the e-ink row width), optional full name (unused by the generated table,
kept for human review).

Not auto-run on every build (vendor OUI data does not change per-build);
rerun by hand after refreshing oui_vendors.tsv:
    python scripts/gen_oui_table.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'scripts', 'data', 'oui_vendors.tsv')
DST = os.path.join(ROOT, 'src', 'activities', 'utilities', 'OuiVendors.h')


def main():
    entries = []
    with open(SRC, encoding='utf-8') as f:
        for line in f:
            line = line.rstrip('\n')
            if not line.strip():
                continue
            parts = line.split('\t')
            oui, short_name = parts[0].strip(), parts[1].strip()
            b = [int(x, 16) for x in oui.split(':')]
            assert len(b) == 3, f'bad OUI: {oui!r}'
            key = (b[0] << 16) | (b[1] << 8) | b[2]
            entries.append((key, short_name))
    entries.sort(key=lambda e: e[0])
    # No duplicate OUIs (a stale re-run appending to the same source would
    # otherwise silently shadow entries at lookup time).
    seen = set()
    for key, _ in entries:
        assert key not in seen, f'duplicate OUI 0x{key:06X} in {SRC}'
        seen.add(key)

    lines = [
        '#pragma once',
        '// Generated by scripts/gen_oui_table.py from scripts/data/oui_vendors.tsv -- do not edit by hand.',
        '#include <cstdint>',
        '',
        'namespace OuiVendors {',
        '',
        'struct Entry {',
        '  uint32_t oui;  // top 24 bits of the MAC, packed as 0x00AABBCC',
        '  const char* name;',
        '};',
        '',
        f'// Sorted by oui ascending ({len(entries)} entries) for binary search.',
        'static constexpr Entry TABLE[] = {',
    ]
    for key, name in entries:
        esc = name.replace('\\', '\\\\').replace('"', '\\"')
        lines.append(f'    {{0x{key:06X}, "{esc}"}},')
    lines += [
        '};',
        '',
        'static constexpr size_t COUNT = sizeof(TABLE) / sizeof(TABLE[0]);',
        '',
        '// Returns the vendor short name for mac[0..2], or nullptr if not in the table.',
        'inline const char* lookup(const uint8_t* mac) {',
        '  const uint32_t key = (static_cast<uint32_t>(mac[0]) << 16) | (static_cast<uint32_t>(mac[1]) << 8) | mac[2];',
        '  size_t lo = 0, hi = COUNT;',
        '  while (lo < hi) {',
        '    const size_t mid = lo + (hi - lo) / 2;',
        '    if (TABLE[mid].oui < key) {',
        '      lo = mid + 1;',
        '    } else {',
        '      hi = mid;',
        '    }',
        '  }',
        '  return (lo < COUNT && TABLE[lo].oui == key) ? TABLE[lo].name : nullptr;',
        '}',
        '',
        '}  // namespace OuiVendors',
    ]
    with open(DST, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'Wrote {len(entries)} entries to {DST}')


if __name__ == '__main__':
    main()
